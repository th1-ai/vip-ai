def test_build_brief_stay_context_reads_as_plain_staff_guidance():
    """SIMULATION.md finding 3: the front-office "stay context" line used to
    read as leaked internal rule-engine text ("this brief would have
    generated by itself...", mid-sentence lowercase starts). It must read as
    a normal sentence a duty manager can act on."""
    brief = build_brief(_profile(), [], rules={"brief_daily": True, "vip_first": True},
                        sections_cfg={}, today=date(2026, 9, 10))
    stay_context = next(l["text"] for l in brief["front_office"] if l["trace"].startswith("rule"))
    lowered = stay_context.lower()
    assert "would have generated" not in lowered
    assert "would have" not in lowered
    # every sentence in the line starts with a capital, not "this"/"they"
    sentences = [s.strip() for s in stay_context.split(". ") if s.strip()]
    for sentence in sentences:
        first_word = sentence.split()[0]
        assert first_word[0].isupper(), f"sentence does not start uppercase: {sentence!r}"


def test_build_brief_stay_context_cadence_and_priority_wording():
    vip = build_brief(_profile(tier="Gold", visits=4), [],
                      rules={"brief_daily": True, "vip_first": True},
                      sections_cfg={}, today=date(2026, 9, 10))
    vip_line = next(l["text"] for l in vip["front_office"] if l["trace"].startswith("rule"))
    assert "automatic daily VIP brief" in vip_line
    assert "ahead of the regular queue" in vip_line

    on_request = build_brief(_profile(tier="Gold", visits=4), [],
                             rules={"brief_daily": False, "vip_first": True},
                             sections_cfg={}, today=date(2026, 9, 10))
    on_request_line = next(l["text"] for l in on_request["front_office"]
                           if l["trace"].startswith("rule"))
    assert "does not run a daily brief" in on_request_line
