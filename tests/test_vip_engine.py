def test_route_preference_known_and_unknown_keys():
    sections = section_of({})
    section, text, trace = route_preference("drinks", "tawny port", sections)
    assert section == "fnb"
    assert text == "Drinks — tawny port"
    assert trace == "preference · drinks"
    # a key with no home in the default map lands in the front_office catch-all
    unknown_section, _, _ = route_preference("shoe_size", "10", sections)
    assert unknown_section == "front_office"


def test_section_of_extends_defaults_without_dropping_them():
    sections = section_of({"housekeeping": ["turndown_note"]})
    assert sections["turndown_note"] == "housekeeping"
    assert sections["drinks"] == "fnb"  # default still present


def _profile(**overrides) -> dict:
    base = {
        "guest_name": "Eleanor Ashby", "tier": "Platinum", "visits": 11,
        "room_type": "Meridian Suite", "arrival_offset": 2, "arrival_date": "2026-09-12",
        "preferences": {"room": "corner suite", "drinks": "tawny port", "occasion": "40th anniversary"},
        "history_note": "Long-time regulars.",
    }
    base.update(overrides)
    return base


def test_build_brief_every_line_has_a_trace():
    snippets = [{"id": "r-1", "source": "press", "headline": "Wine feature",
                "body": "A short mention.", "provenance": "public source — staff verified"}]
    brief = build_brief(_profile(), snippets, rules={"brief_daily": True, "vip_first": True},
                        sections_cfg={}, today=date(2026, 9, 10))
    all_lines = brief["housekeeping"] + brief["fnb"] + brief["front_office"]
    assert all_lines, "expected at least one desk line"
    for line in all_lines:
        assert line["trace"], f"line with no trace: {line}"
    assert brief["gm_line"].startswith("Eleanor Ashby —")
    assert "wine feature" in brief["gm_line"].lower()


